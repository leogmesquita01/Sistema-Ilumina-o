-- ============================================================================
-- 000_esquema_base.sql — tabelas postes e ordens_servico (como estão em produção)
-- ============================================================================
-- Estas tabelas foram criadas pelo painel do Supabase antes das migrações
-- versionadas. Este arquivo existe para que o banco possa ser recriado do zero
-- (ambiente de teste, nova prefeitura) rodando 000 → 001 → 002 → 003 → 004.
-- É idempotente: num banco que já tem as tabelas, não faz nada.
-- ============================================================================

create table if not exists public.postes (
  id               bigint generated by default as identity primary key,
  codigo           text not null unique,
  latitude         double precision,
  longitude        double precision,
  logradouro       text default 'Não informado',
  bairro           text default 'Centro',
  referencia       text default '',
  tipo_luminaria   text default 'LED',
  potencia         integer default 100,
  tipo_poste       text default 'Concreto Duplo T',
  tipo_braco       text default 'Braço Médio 2m',
  status           text default 'normal',
  observacoes      text default '',
  data_atualizacao timestamptz default now()
);

create table if not exists public.ordens_servico (
  id             bigint generated by default as identity primary key,
  protocolo      text not null unique,
  codigo_poste   text not null references public.postes (codigo) on update cascade on delete cascade,
  defeito        text not null,
  prioridade     text default 'Normal',
  materiais      text default '[]',
  solicitante    text default 'Secretaria de Infraestrutura',
  status         text default 'aberta',
  data_abertura  timestamptz default now(),
  data_conclusao timestamptz,
  observacoes    text default ''
);

create index if not exists idx_postes_codigo     on public.postes (codigo);
create index if not exists idx_postes_status     on public.postes (status);
create index if not exists idx_os_codigo_poste   on public.ordens_servico (codigo_poste);
create index if not exists idx_os_status         on public.ordens_servico (status);
